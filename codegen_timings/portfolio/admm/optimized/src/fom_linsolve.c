void fom_lin_solve_t3(const fom_float *b, fom_float *x) {
    fom_float y[FOM_FAC_T3_DIM];
    fom_int i, j, p, r;
    for (i = 0; i < FOM_FAC_T3_DIM; ++i) y[i] = b[FOM_FAC_T3_PERM[i]];
    /* forward solve: unit lower-triangular L y = P^T b */
    for (j = 0; j < FOM_FAC_T3_DIM; ++j) {
        for (p = FOM_FAC_T3_L_INDPTR[j]; p < FOM_FAC_T3_L_INDPTR[j + 1]; ++p) {
            r = FOM_FAC_T3_L_INDICES[p];
            if (r != j) y[r] -= FOM_FAC_T3_L_DATA[p] * y[j];
        }
    }
    /* diagonal solve (multiply by reciprocals) */
    for (i = 0; i < FOM_FAC_T3_DIM; ++i) y[i] *= FOM_FAC_T3_DINV[i];
    /* backward solve in place: unit upper-triangular L^T y = y */
    for (j = FOM_FAC_T3_DIM - 1; j >= 0; --j) {
        for (p = FOM_FAC_T3_L_INDPTR[j]; p < FOM_FAC_T3_L_INDPTR[j + 1]; ++p) {
            r = FOM_FAC_T3_L_INDICES[p];
            if (r > j) y[j] -= FOM_FAC_T3_L_DATA[p] * y[r];
        }
    }
    /* symmetric scatter: x[perm[i]] = y[i] */
    for (i = 0; i < FOM_FAC_T3_DIM; ++i) x[FOM_FAC_T3_PERM[i]] = y[i];
}
