static inline void act_clip(fom_float *x, const fom_float *lo, const fom_float *hi, int n) {
    for (int i = 0; i < n; i++) { fom_float v = x[i]; v = v < lo[i] ? lo[i] : v; x[i] = v > hi[i] ? hi[i] : v; }
}
static inline void act_relu(fom_float *x, int n) {
    for (int i = 0; i < n; i++) x[i] = x[i] > 0 ? x[i] : 0;
}

void fom_set_default_settings(FomSettings *s) { s->max_iter = FOM_MAX_ITER; s->tol = FOM_TOL; s->check_termination = FOM_CHECK_TERMINATION; }
void fom_setup(FomWorkspace *w, const FomSettings *s) {
    w->settings = *s;
    memcpy(w->state, FOM_STATE_INIT, sizeof(w->state));
    w->solution.iter = 0; w->solution.residual = 0; w->solution.status = 0;
}
void fom_update_params(FomWorkspace *w, const FomParams *p) {
    w->params = *p;
    memcpy(w->state, FOM_STATE_INIT, sizeof(w->state));
}
void fom_cleanup(FomWorkspace *w) { (void)w; }

